BEGIN;

CREATE TABLE IF NOT EXISTS public.import_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_type VARCHAR(32) NOT NULL
        CHECK (source_type IN (
            'EMPLOYEE_MASTER',
            'SALARY_ENTITLEMENTS',
            'PAYROLL_HISTORY',
            'SALARY_REVISIONS'
        )),

    status VARCHAR(32) NOT NULL DEFAULT 'UPLOADED'
        CHECK (status IN (
            'UPLOADED',
            'VALIDATING',
            'VALIDATED',
            'HAS_ERRORS',
            'AWAITING_APPROVAL',
            'APPROVED',
            'IMPORTING',
            'PARTIALLY_IMPORTED',
            'IMPORTED',
            'FAILED',
            'CANCELLED'
        )),

    file_name VARCHAR(255) NOT NULL,
    file_key TEXT NOT NULL,
    file_sha256 CHAR(64) NOT NULL
        CHECK (file_sha256 ~ '^[0-9a-fA-F]{64}$'),

    detected_format VARCHAR(100),
    source_mapping JSONB NOT NULL DEFAULT '{}'::jsonb,

    date_range_start DATE,
    date_range_end DATE,
    period_count INTEGER NOT NULL DEFAULT 0
        CHECK (period_count >= 0),

    total_rows INTEGER NOT NULL DEFAULT 0
        CHECK (total_rows >= 0),
    valid_rows INTEGER NOT NULL DEFAULT 0
        CHECK (valid_rows >= 0),
    error_rows INTEGER NOT NULL DEFAULT 0
        CHECK (error_rows >= 0),
    warning_rows INTEGER NOT NULL DEFAULT 0
        CHECK (warning_rows >= 0),

    uploaded_by BIGINT NOT NULL REFERENCES public.users(id),
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    approved_by BIGINT REFERENCES public.users(id),
    approved_at TIMESTAMPTZ,
    validated_at TIMESTAMPTZ,
    imported_at TIMESTAMPTZ,

    failure_reason TEXT,
    notes TEXT,

    CONSTRAINT chk_import_jobs_date_range
        CHECK (
            date_range_start IS NULL
            OR date_range_end IS NULL
            OR date_range_end >= date_range_start
        ),

    CONSTRAINT chk_import_jobs_maker_checker
        CHECK (
            approved_by IS NULL
            OR approved_by <> uploaded_by
        )
);

ALTER TABLE public.import_batches
    ADD COLUMN IF NOT EXISTS import_job_id BIGINT
        REFERENCES public.import_jobs(id);

CREATE INDEX IF NOT EXISTS ix_import_jobs_uploaded_by
    ON public.import_jobs(uploaded_by, uploaded_at DESC);

CREATE INDEX IF NOT EXISTS ix_import_jobs_file_sha256
    ON public.import_jobs(file_sha256);

CREATE INDEX IF NOT EXISTS ix_import_batches_job
    ON public.import_batches(import_job_id);

-- Allow period-specific staging batches for historical payroll.
ALTER TABLE public.import_batches
    DROP CONSTRAINT IF EXISTS import_batches_import_type_check;

ALTER TABLE public.import_batches
    ADD CONSTRAINT import_batches_import_type_check
    CHECK (
        import_type IN (
            'EMPLOYEES',
            'SALARY_VALUES',
            'REVISIONS',
            'PAYROLL_HISTORY'
        )
    );

-- Protect the parent upload record with RLS.
ALTER TABLE public.import_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.import_jobs FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS import_jobs_select_policy
    ON public.import_jobs;

CREATE POLICY import_jobs_select_policy
ON public.import_jobs
FOR SELECT
TO ssga_app
USING (
    uploaded_by = app.current_user_id()
    OR EXISTS (
        SELECT 1
        FROM public.import_batches b
        WHERE b.import_job_id = import_jobs.id
    )
);

DROP POLICY IF EXISTS import_jobs_insert_policy
    ON public.import_jobs;

CREATE POLICY import_jobs_insert_policy
ON public.import_jobs
FOR INSERT
TO ssga_app
WITH CHECK (
    uploaded_by = app.current_user_id()
);

DROP POLICY IF EXISTS import_jobs_update_policy
    ON public.import_jobs;

CREATE POLICY import_jobs_update_policy
ON public.import_jobs
FOR UPDATE
TO ssga_app
USING (
    uploaded_by = app.current_user_id()
)
WITH CHECK (
    uploaded_by = app.current_user_id()
);

GRANT SELECT, INSERT, UPDATE
ON public.import_jobs
TO ssga_app;

COMMIT;
