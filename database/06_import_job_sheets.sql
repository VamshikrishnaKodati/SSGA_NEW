BEGIN;

CREATE TABLE IF NOT EXISTS public.import_job_sheets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    import_job_id BIGINT NOT NULL
        REFERENCES public.import_jobs(id) ON DELETE CASCADE,

    sheet_index INTEGER NOT NULL CHECK (sheet_index >= 0),
    sheet_name VARCHAR(255) NOT NULL,

    suggested_type VARCHAR(64) NOT NULL DEFAULT 'UNKNOWN',

    confirmed_type VARCHAR(32)
        CHECK (
            confirmed_type IS NULL OR confirmed_type IN (
                'EMPLOYEE_MASTER',
                'SALARY_ENTITLEMENTS',
                'PAYROLL_HISTORY',
                'SALARY_REVISIONS',
                'REFERENCE_ONLY',
                'SKIP'
            )
        ),

    status VARCHAR(24) NOT NULL DEFAULT 'DETECTED'
        CHECK (
            status IN (
                'DETECTED',
                'MAPPED',
                'VALIDATING',
                'VALIDATED',
                'HAS_ERRORS',
                'READY',
                'IMPORTED',
                'SKIPPED',
                'FAILED'
            )
        ),

    header_row_number INTEGER
        CHECK (header_row_number IS NULL OR header_row_number > 0),

    column_count INTEGER NOT NULL DEFAULT 0
        CHECK (column_count >= 0),

    non_empty_rows INTEGER NOT NULL DEFAULT 0
        CHECK (non_empty_rows >= 0),

    data_rows_estimate INTEGER NOT NULL DEFAULT 0
        CHECK (data_rows_estimate >= 0),

    headers JSONB NOT NULL DEFAULT '[]'::jsonb,
    column_mapping JSONB NOT NULL DEFAULT '{}'::jsonb,
    validation_summary JSONB NOT NULL DEFAULT '{}'::jsonb,

    valid_rows INTEGER NOT NULL DEFAULT 0
        CHECK (valid_rows >= 0),

    error_rows INTEGER NOT NULL DEFAULT 0
        CHECK (error_rows >= 0),

    warning_rows INTEGER NOT NULL DEFAULT 0
        CHECK (warning_rows >= 0),

    confirmed_by BIGINT REFERENCES public.users(id),
    confirmed_at TIMESTAMPTZ,
    validated_at TIMESTAMPTZ,
    imported_at TIMESTAMPTZ,

    notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_import_job_sheet_index
        UNIQUE (import_job_id, sheet_index)
);

-- Link each period-specific staging batch to its source worksheet.
ALTER TABLE public.import_batches
    ADD COLUMN IF NOT EXISTS import_job_sheet_id BIGINT
        REFERENCES public.import_job_sheets(id);

CREATE INDEX IF NOT EXISTS ix_import_job_sheets_job
    ON public.import_job_sheets(import_job_id, sheet_index);

CREATE INDEX IF NOT EXISTS ix_import_job_sheets_status
    ON public.import_job_sheets(import_job_id, status);

CREATE INDEX IF NOT EXISTS ix_import_batches_job_sheet
    ON public.import_batches(import_job_sheet_id);

ALTER TABLE public.import_job_sheets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.import_job_sheets FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS import_job_sheets_select_policy
    ON public.import_job_sheets;

CREATE POLICY import_job_sheets_select_policy
ON public.import_job_sheets
FOR SELECT
TO ssga_app
USING (
    EXISTS (
        SELECT 1
        FROM public.import_jobs j
        WHERE j.id = import_job_sheets.import_job_id
          AND j.uploaded_by = app.current_user_id()
    )
);

DROP POLICY IF EXISTS import_job_sheets_insert_policy
    ON public.import_job_sheets;

CREATE POLICY import_job_sheets_insert_policy
ON public.import_job_sheets
FOR INSERT
TO ssga_app
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.import_jobs j
        WHERE j.id = import_job_sheets.import_job_id
          AND j.uploaded_by = app.current_user_id()
    )
);

DROP POLICY IF EXISTS import_job_sheets_update_policy
    ON public.import_job_sheets;

CREATE POLICY import_job_sheets_update_policy
ON public.import_job_sheets
FOR UPDATE
TO ssga_app
USING (
    EXISTS (
        SELECT 1
        FROM public.import_jobs j
        WHERE j.id = import_job_sheets.import_job_id
          AND j.uploaded_by = app.current_user_id()
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.import_jobs j
        WHERE j.id = import_job_sheets.import_job_id
          AND j.uploaded_by = app.current_user_id()
    )
);

GRANT SELECT, INSERT, UPDATE
ON public.import_job_sheets
TO ssga_app;

GRANT USAGE, SELECT
ON SEQUENCE public.import_job_sheets_id_seq
TO ssga_app;

COMMIT;