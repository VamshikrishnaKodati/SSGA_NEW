-- ============================================================================
-- 11_employee_master_and_components.sql
--
-- Additive migration for the "Complete Employee Master and All 42 Salary
-- Components" scope. Safe to re-run: every statement is guarded
-- (IF NOT EXISTS / ON CONFLICT / DROP POLICY IF EXISTS).
--
-- Adds:
--   1. circles master (organization scoped)
--   2. wards master (division scoped)
--   3. employees.circle_id / employees.ward_id
--   4. employee_bank_accounts (history-capable, RLS protected)
--   5. Seed of all 42 approved salary components
--
-- Statutory / personal identifiers (PAN, Aadhaar, PF, NPS, GPF, EMAIL) are
-- NOT new columns: they are stored in the existing employee_identity_mappings
-- table (identity_type, identity_value) which already enforces
-- UNIQUE (identity_type, identity_value).
--
-- Uniqueness of employees.employee_code and employees.hrms_id and
-- salary_components.component_code is ALREADY enforced by existing
-- constraints, so no new index is required here.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. circles master
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.circles (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES public.organizations(id),
    name            character varying(150) NOT NULL,
    code            character varying(50)  NOT NULL,
    status          character varying(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at      timestamp with time zone NOT NULL DEFAULT now(),
    updated_at      timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT circles_organization_code_key UNIQUE (organization_id, code)
);

-- ---------------------------------------------------------------------------
-- 2. wards master (belongs to a division)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.wards (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_id bigint NOT NULL REFERENCES public.divisions(id),
    name        character varying(150) NOT NULL,
    code        character varying(50)  NOT NULL,
    status      character varying(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at  timestamp with time zone NOT NULL DEFAULT now(),
    updated_at  timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT wards_division_code_key UNIQUE (division_id, code)
);

-- ---------------------------------------------------------------------------
-- 3. employees: optional circle / ward placement
-- ---------------------------------------------------------------------------
ALTER TABLE public.employees
    ADD COLUMN IF NOT EXISTS circle_id bigint REFERENCES public.circles(id);
ALTER TABLE public.employees
    ADD COLUMN IF NOT EXISTS ward_id bigint REFERENCES public.wards(id);

CREATE INDEX IF NOT EXISTS ix_employees_circle_id
    ON public.employees (circle_id);
CREATE INDEX IF NOT EXISTS ix_employees_ward_id
    ON public.employees (ward_id);

-- ---------------------------------------------------------------------------
-- 4. employee_bank_accounts (supports history; one active primary per employee)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.employee_bank_accounts (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id    bigint NOT NULL REFERENCES public.employees(id),
    bank_name      character varying(150) NOT NULL,
    branch_name    character varying(150),
    account_number character varying(34)  NOT NULL,
    ifsc_code      character varying(11),
    is_primary     boolean NOT NULL DEFAULT true,
    status         character varying(20) NOT NULL DEFAULT 'ACTIVE',
    effective_from date NOT NULL DEFAULT CURRENT_DATE,
    effective_to   date,
    created_at     timestamp with time zone NOT NULL DEFAULT now(),
    updated_at     timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT employee_bank_accounts_employee_account_key
        UNIQUE (employee_id, account_number),
    CONSTRAINT employee_bank_accounts_dates_check
        CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

CREATE INDEX IF NOT EXISTS ix_employee_bank_accounts_employee_id
    ON public.employee_bank_accounts (employee_id);

-- ---------------------------------------------------------------------------
-- 5. Row level security + grants
--    circles / wards are read-only masters (like designations / grades).
--    employee_bank_accounts carries sensitive data, so it is scoped per
--    employee exactly like employee_identity_mappings / employee_salary_values.
-- ---------------------------------------------------------------------------
ALTER TABLE public.circles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.wards   ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS circles_read_policy ON public.circles;
CREATE POLICY circles_read_policy ON public.circles
    FOR SELECT USING (true);

DROP POLICY IF EXISTS wards_read_policy ON public.wards;
CREATE POLICY wards_read_policy ON public.wards
    FOR SELECT USING (true);

ALTER TABLE public.employee_bank_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.employee_bank_accounts FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS employee_bank_accounts_scope_policy
    ON public.employee_bank_accounts;
CREATE POLICY employee_bank_accounts_scope_policy
    ON public.employee_bank_accounts
    USING (app.can_access_employee(employee_id))
    WITH CHECK (app.can_access_employee(employee_id));

GRANT SELECT ON public.circles, public.wards TO ssga_app;
GRANT SELECT, INSERT, UPDATE ON public.employee_bank_accounts TO ssga_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ssga_app;

