BEGIN;

CREATE TABLE IF NOT EXISTS public.import_job_sheet_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    import_job_sheet_id BIGINT NOT NULL
        REFERENCES public.import_job_sheets(id) ON DELETE CASCADE,

    source_row_number INTEGER NOT NULL
        CHECK (source_row_number > 0),

    severity VARCHAR(16) NOT NULL
        CHECK (severity IN ('ERROR', 'WARNING')),

    field_name VARCHAR(100),
    error_code VARCHAR(80) NOT NULL,
    message TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_import_sheet_issues_row
    ON public.import_job_sheet_issues(
        import_job_sheet_id,
        source_row_number
    );

CREATE INDEX IF NOT EXISTS ix_import_sheet_issues_severity
    ON public.import_job_sheet_issues(
        import_job_sheet_id,
        severity
    );

ALTER TABLE public.import_job_sheet_issues
    ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.import_job_sheet_issues
    FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS import_job_sheet_issues_scope_policy
    ON public.import_job_sheet_issues;

CREATE POLICY import_job_sheet_issues_scope_policy
ON public.import_job_sheet_issues
FOR ALL
TO ssga_app
USING (
    EXISTS (
        SELECT 1
        FROM public.import_job_sheets s
        JOIN public.import_jobs j
          ON j.id = s.import_job_id
        WHERE s.id = import_job_sheet_issues.import_job_sheet_id
          AND j.uploaded_by = app.current_user_id()
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.import_job_sheets s
        JOIN public.import_jobs j
          ON j.id = s.import_job_id
        WHERE s.id = import_job_sheet_issues.import_job_sheet_id
          AND j.uploaded_by = app.current_user_id()
    )
);

GRANT SELECT, INSERT, DELETE
ON public.import_job_sheet_issues
TO ssga_app;

GRANT USAGE, SELECT
ON SEQUENCE public.import_job_sheet_issues_id_seq
TO ssga_app;

COMMIT;