BEGIN;

CREATE TABLE IF NOT EXISTS public.import_job_progress_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_job_id BIGINT NOT NULL
        REFERENCES public.import_jobs(id) ON DELETE CASCADE,
    actor_user_id BIGINT NOT NULL REFERENCES public.users(id),
    status VARCHAR(32) NOT NULL,
    level VARCHAR(16) NOT NULL,
    message TEXT NOT NULL,
    total_records INTEGER NOT NULL CHECK (total_records >= 0),
    processed_records INTEGER NOT NULL CHECK (processed_records >= 0),
    imported_rows INTEGER NOT NULL CHECK (imported_rows >= 0),
    skipped_rows INTEGER NOT NULL CHECK (skipped_rows >= 0),
    failed_rows INTEGER NOT NULL CHECK (failed_rows >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_import_job_progress_events_job_v30
    ON public.import_job_progress_events (import_job_id, id DESC);

ALTER TABLE public.import_job_progress_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.import_job_progress_events FORCE ROW LEVEL SECURITY;

GRANT SELECT, INSERT ON public.import_job_progress_events TO ssga_app;
GRANT USAGE, SELECT
    ON SEQUENCE public.import_job_progress_events_id_seq TO ssga_app;

DROP POLICY IF EXISTS import_job_progress_events_select_v30
    ON public.import_job_progress_events;
CREATE POLICY import_job_progress_events_select_v30
    ON public.import_job_progress_events FOR SELECT TO ssga_app
    USING (
        EXISTS (
            SELECT 1
            FROM public.import_jobs j
            WHERE j.id = import_job_progress_events.import_job_id
              AND j.uploaded_by = app.current_user_id()
        )
        OR app.has_import_job_assignment(
            import_job_progress_events.import_job_id,
            ARRAY['RESOLVER','APPROVER','FINALIZER','VIEWER']::TEXT[],
            NULL
        )
    );

DROP POLICY IF EXISTS import_job_progress_events_insert_v30
    ON public.import_job_progress_events;
CREATE POLICY import_job_progress_events_insert_v30
    ON public.import_job_progress_events FOR INSERT TO ssga_app
    WITH CHECK (
        actor_user_id = app.current_user_id()
        AND (
            EXISTS (
                SELECT 1
                FROM public.import_jobs j
                WHERE j.id = import_job_progress_events.import_job_id
                  AND j.uploaded_by = app.current_user_id()
            )
            OR app.has_import_job_assignment(
                import_job_progress_events.import_job_id,
                ARRAY['RESOLVER','APPROVER','FINALIZER']::TEXT[],
                NULL
            )
        )
    );

INSERT INTO public.schema_migrations (version, name)
VALUES (30, '30_import_job_progress')
ON CONFLICT (version) DO NOTHING;

COMMIT;
