-- ============================================================
-- SSGA NEW - 13. IMPORT MAPPING PROFILES (additive)
-- PostgreSQL 17
-- ============================================================
--
-- Reusable, saved column-mapping profiles so the same workbook shape does not
-- have to be re-mapped by hand every time. A profile is keyed to the import
-- type and a fingerprint of the sheet's column structure
-- (structure_signature), so a changed template can be detected before it is
-- applied. Profiles are metadata only; they never contain salary values.
--
-- Visibility: a profile is private to its creator, or shared (is_shared) so
-- that other preparers can reuse it. Rows are protected by RLS and the runtime
-- role only receives the privileges it needs.
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.import_mapping_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(120) NOT NULL,

    import_type VARCHAR(32) NOT NULL
        CHECK (import_type IN (
            'EMPLOYEE_MASTER',
            'SALARY_ENTITLEMENTS',
            'PAYROLL_HISTORY',
            'SALARY_REVISIONS'
        )),

    -- SHA-256 fingerprint of the normalized source headers.
    structure_signature VARCHAR(64) NOT NULL
        CHECK (structure_signature ~ '^[0-9a-fA-F]{64}$'),

    schema_version INTEGER NOT NULL DEFAULT 1
        CHECK (schema_version > 0),

    column_mapping JSONB NOT NULL DEFAULT '{}'::jsonb,
    options JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_by BIGINT NOT NULL REFERENCES public.users(id),

    -- When true the profile is visible to any user for reuse.
    is_shared BOOLEAN NOT NULL DEFAULT FALSE,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_import_mapping_profile
        UNIQUE (created_by, import_type, name)
);

CREATE INDEX IF NOT EXISTS ix_import_mapping_profiles_type
    ON public.import_mapping_profiles(import_type, structure_signature);

CREATE INDEX IF NOT EXISTS ix_import_mapping_profiles_owner
    ON public.import_mapping_profiles(created_by, is_active);

ALTER TABLE public.import_mapping_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.import_mapping_profiles FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS import_mapping_profiles_select_policy
    ON public.import_mapping_profiles;

CREATE POLICY import_mapping_profiles_select_policy
ON public.import_mapping_profiles
FOR SELECT
TO ssga_app
USING (
    created_by = app.current_user_id()
    OR is_shared
);

DROP POLICY IF EXISTS import_mapping_profiles_insert_policy
    ON public.import_mapping_profiles;

CREATE POLICY import_mapping_profiles_insert_policy
ON public.import_mapping_profiles
FOR INSERT
TO ssga_app
WITH CHECK (
    created_by = app.current_user_id()
);

DROP POLICY IF EXISTS import_mapping_profiles_update_policy
    ON public.import_mapping_profiles;

CREATE POLICY import_mapping_profiles_update_policy
ON public.import_mapping_profiles
FOR UPDATE
TO ssga_app
USING (
    created_by = app.current_user_id()
)
WITH CHECK (
    created_by = app.current_user_id()
);

DROP POLICY IF EXISTS import_mapping_profiles_delete_policy
    ON public.import_mapping_profiles;

CREATE POLICY import_mapping_profiles_delete_policy
ON public.import_mapping_profiles
FOR DELETE
TO ssga_app
USING (
    created_by = app.current_user_id()
);

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.import_mapping_profiles
TO ssga_app;

GRANT USAGE, SELECT
ON SEQUENCE public.import_mapping_profiles_id_seq
TO ssga_app;

COMMIT;
