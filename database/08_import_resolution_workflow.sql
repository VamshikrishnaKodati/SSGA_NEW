            WHERE a.import_job_id = import_job_workflow_events.import_job_id
              AND a.user_id = app.current_user_id()
              AND a.is_active
              AND a.assignment_role IN ('RESOLVER','APPROVER','FINALIZER','VIEWER')
              AND (
                  a.division_id IS NULL
                  OR (import_job_workflow_events.division_id IS NOT NULL
                      AND a.division_id = import_job_workflow_events.division_id)
              )
        )
    );

DROP POLICY IF EXISTS import_job_workflow_events_insert_v08 ON public.import_job_workflow_events;
CREATE POLICY import_job_workflow_events_insert_v08
    ON public.import_job_workflow_events FOR INSERT TO ssga_app
    WITH CHECK (
        actor_user_id = app.current_user_id()
        AND (
            EXISTS (
                SELECT 1 FROM public.import_jobs j
                WHERE j.id = import_job_workflow_events.import_job_id
                  AND j.uploaded_by = app.current_user_id()
            )
            OR EXISTS (
                SELECT 1 FROM public.import_job_assignments a
                WHERE a.import_job_id = import_job_workflow_events.import_job_id
