-- Assignment identity and scope cannot be mutated after assignment; revoke the
-- old assignment and create a new one instead.
CREATE OR REPLACE FUNCTION app.guard_import_job_assignment_identity_v08()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public, app
AS $$
BEGIN
    IF NEW.import_job_id IS DISTINCT FROM OLD.import_job_id
       OR NEW.user_id IS DISTINCT FROM OLD.user_id
       OR NEW.assignment_role IS DISTINCT FROM OLD.assignment_role
       OR NEW.division_id IS DISTINCT FROM OLD.division_id
       OR NEW.assigned_by IS DISTINCT FROM OLD.assigned_by THEN
        RAISE EXCEPTION 'Import assignment identity and scope are immutable; revoke and create a new assignment';
    END IF;
    IF OLD.is_active = FALSE AND NEW.is_active = TRUE THEN
        RAISE EXCEPTION 'A revoked import assignment cannot be reactivated; create a new assignment';
    END IF;
    IF OLD.is_active = TRUE AND NEW.is_active = FALSE AND NEW.revoked_at IS NULL THEN
        NEW.revoked_at := now();
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_guard_import_job_assignment_identity_v08 ON public.import_job_assignments;
CREATE TRIGGER trg_guard_import_job_assignment_identity_v08
    BEFORE UPDATE ON public.import_job_assignments
    FOR EACH ROW EXECUTE FUNCTION app.guard_import_job_assignment_identity_v08();

