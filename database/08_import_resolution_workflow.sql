                      a.division_id IS NULL
                      OR (import_job_workflow_events.division_id IS NOT NULL
                          AND a.division_id = import_job_workflow_events.division_id)
                  )
            )
        )
    );

-- Protect source-file identity and the uploader identity from edits. Workflow
-- state transitions are enforced in the Java service in the next implementation
-- step; this trigger ensures the original source cannot be silently swapped.
CREATE OR REPLACE FUNCTION app.guard_import_job_source_identity_v08()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public, app
AS $$
BEGIN
    IF NEW.uploaded_by IS DISTINCT FROM OLD.uploaded_by
       OR NEW.file_name IS DISTINCT FROM OLD.file_name
       OR NEW.file_key IS DISTINCT FROM OLD.file_key
       OR NEW.file_sha256 IS DISTINCT FROM OLD.file_sha256 THEN
        RAISE EXCEPTION 'Import job owner and source-file identity are immutable';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_guard_import_job_source_identity_v08 ON public.import_jobs;
CREATE TRIGGER trg_guard_import_job_source_identity_v08
    BEFORE UPDATE ON public.import_jobs
    FOR EACH ROW EXECUTE FUNCTION app.guard_import_job_source_identity_v08();

