-- ---------------------------------------------------------------------------
-- 1. Extend the existing import-job record with explicit workflow milestones.
-- Existing status CHECK already supports AWAITING_APPROVAL, APPROVED, IMPORTING,
-- IMPORTED and related states, so it is intentionally left unchanged.
-- ---------------------------------------------------------------------------
ALTER TABLE public.import_jobs
    ADD COLUMN IF NOT EXISTS submitted_by BIGINT REFERENCES public.users(id),
    ADD COLUMN IF NOT EXISTS submitted_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS finalized_by BIGINT REFERENCES public.users(id),
    ADD COLUMN IF NOT EXISTS finalized_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS rejection_reason TEXT,
    ADD COLUMN IF NOT EXISTS resolution_version INTEGER NOT NULL DEFAULT 1;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.import_jobs'::regclass
          AND conname = 'chk_import_jobs_approval_separation_v08'
    ) THEN
        ALTER TABLE public.import_jobs
            ADD CONSTRAINT chk_import_jobs_approval_separation_v08
            CHECK (
                approved_by IS NULL
                OR (approved_by <> uploaded_by
                    AND (submitted_by IS NULL OR approved_by <> submitted_by))
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.import_jobs'::regclass
          AND conname = 'chk_import_jobs_finalizer_separation_v08'
    ) THEN
        ALTER TABLE public.import_jobs
            ADD CONSTRAINT chk_import_jobs_finalizer_separation_v08
            CHECK (
                finalized_by IS NULL
                OR (approved_by IS NOT NULL
                    AND finalized_by <> uploaded_by
                    AND (submitted_by IS NULL OR finalized_by <> submitted_by)
                    AND finalized_by <> approved_by)
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.import_jobs'::regclass
          AND conname = 'chk_import_jobs_submitted_pair_v08'
    ) THEN
        ALTER TABLE public.import_jobs
            ADD CONSTRAINT chk_import_jobs_submitted_pair_v08
            CHECK ((submitted_by IS NULL) = (submitted_at IS NULL));
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.import_jobs'::regclass
          AND conname = 'chk_import_jobs_finalized_pair_v08'
    ) THEN
        ALTER TABLE public.import_jobs
            ADD CONSTRAINT chk_import_jobs_finalized_pair_v08
            CHECK ((finalized_by IS NULL) = (finalized_at IS NULL));
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.import_jobs'::regclass
          AND conname = 'chk_import_jobs_resolution_version_v08'
    ) THEN
        ALTER TABLE public.import_jobs
            ADD CONSTRAINT chk_import_jobs_resolution_version_v08
            CHECK (resolution_version >= 1);
    END IF;
END $$;

