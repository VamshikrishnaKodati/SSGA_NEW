-- ---------------------------------------------------------------------------
-- 5. Row-level security helpers. SECURITY DEFINER is limited to these lookup
-- helpers to avoid policy recursion between import_jobs and assignments.
-- app.current_user_id() remains the source of the authenticated user identity.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app.has_import_job_assignment(
    p_import_job_id BIGINT,
    p_roles TEXT[] DEFAULT NULL,
    p_division_id BIGINT DEFAULT NULL
)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, app
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.import_job_assignments a
        WHERE a.import_job_id = p_import_job_id
          AND a.user_id = app.current_user_id()
          AND a.is_active
          AND (p_roles IS NULL OR a.assignment_role = ANY (p_roles))
          AND (
              p_division_id IS NULL
              OR a.division_id IS NULL
              OR a.division_id = p_division_id
          )
    );
$$;

REVOKE ALL ON FUNCTION app.has_import_job_assignment(BIGINT, TEXT[], BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION app.has_import_job_assignment(BIGINT, TEXT[], BIGINT) TO ssga_app;

