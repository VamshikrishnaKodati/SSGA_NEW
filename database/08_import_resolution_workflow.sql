-- Assignment-aware issue policy. A division-scoped assignment only sees issues
-- whose target_division_id is known and matches; unknown/unattributed issues
-- remain visible only to the uploader or a job-wide assignee.
DROP POLICY IF EXISTS import_job_sheet_issues_assigned_select_v08 ON public.import_job_sheet_issues;
CREATE POLICY import_job_sheet_issues_assigned_select_v08
    ON public.import_job_sheet_issues FOR SELECT TO ssga_app
    USING (
        EXISTS (
            SELECT 1
            FROM public.import_job_sheets s
            WHERE s.id = import_job_sheet_issues.import_job_sheet_id
              AND (
                  app.has_import_job_assignment(s.import_job_id,
                      ARRAY['RESOLVER','APPROVER','FINALIZER','VIEWER']::TEXT[], NULL)
                  AND (
                      EXISTS (
                          SELECT 1 FROM public.import_job_assignments a
                          WHERE a.import_job_id = s.import_job_id
                            AND a.user_id = app.current_user_id()
                            AND a.is_active
                            AND a.division_id IS NULL
                            AND a.assignment_role IN ('RESOLVER','APPROVER','FINALIZER','VIEWER')
                      )
                      OR (
                          import_job_sheet_issues.target_division_id IS NOT NULL
                          AND EXISTS (
                              SELECT 1 FROM public.import_job_assignments a
                              WHERE a.import_job_id = s.import_job_id
                                AND a.user_id = app.current_user_id()
                                AND a.is_active
                                AND a.division_id = import_job_sheet_issues.target_division_id
                                AND a.assignment_role IN ('RESOLVER','APPROVER','FINALIZER','VIEWER')
                          )
                      )
                  )
              )
        )
    );

