-- ============================================================================
-- 27_payroll_history_imports.sql
--
-- Stores imported payroll history independently from operational payroll
-- batches, transactions, approvals, and statements.
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.payroll_history_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES public.employees(id),
    salary_component_id BIGINT NOT NULL
        REFERENCES public.salary_components(id),
    payroll_period DATE NOT NULL
        CHECK (EXTRACT(DAY FROM payroll_period) = 1),
    employee_code_snapshot VARCHAR(50) NOT NULL,
    hrms_id_snapshot VARCHAR(20) NOT NULL,
    employee_name_snapshot VARCHAR(150) NOT NULL,
    component_code_snapshot VARCHAR(50) NOT NULL,
    component_name_snapshot VARCHAR(150) NOT NULL,
    category_snapshot VARCHAR(20) NOT NULL
        CHECK (category_snapshot IN ('EARNING', 'DEDUCTION')),
    amount NUMERIC(15,2) NOT NULL CHECK (amount >= 0),
    gross_salary NUMERIC(15,2) CHECK (gross_salary >= 0),
    total_deductions NUMERIC(15,2) CHECK (total_deductions >= 0),
    net_salary NUMERIC(15,2) CHECK (net_salary >= 0),
    source_status TEXT,
    source_file_name VARCHAR(255) NOT NULL,
    source_file_sha256 CHAR(64) NOT NULL
        CHECK (source_file_sha256 ~ '^[0-9a-fA-F]{64}$'),
    source_sheet_name VARCHAR(255) NOT NULL,
    source_row_number INTEGER NOT NULL CHECK (source_row_number > 0),
    source_values JSONB NOT NULL,
    import_job_id BIGINT NOT NULL
        REFERENCES public.import_jobs(id) ON DELETE RESTRICT,
    import_job_sheet_id BIGINT NOT NULL
        REFERENCES public.import_job_sheets(id) ON DELETE RESTRICT,
    imported_by BIGINT NOT NULL REFERENCES public.users(id),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT payroll_history_records_totals_check
        CHECK (
            (
                gross_salary IS NULL
                AND total_deductions IS NULL
                AND net_salary IS NULL
            )
            OR (
                gross_salary IS NOT NULL
                AND total_deductions IS NOT NULL
                AND net_salary IS NOT NULL
                AND net_salary = gross_salary - total_deductions
            )
        ),
    CONSTRAINT payroll_history_records_period_component_unique
        UNIQUE (employee_id, payroll_period, salary_component_id),
    CONSTRAINT payroll_history_records_source_row_unique
        UNIQUE (import_job_sheet_id, source_row_number)
);

CREATE INDEX IF NOT EXISTS ix_payroll_history_records_employee_period
    ON public.payroll_history_records(employee_id, payroll_period);

CREATE INDEX IF NOT EXISTS ix_payroll_history_records_import_job
    ON public.payroll_history_records(import_job_id, import_job_sheet_id);

ALTER TABLE public.payroll_history_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payroll_history_records FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS payroll_history_records_scope_policy
    ON public.payroll_history_records;

CREATE POLICY payroll_history_records_scope_policy
ON public.payroll_history_records
FOR ALL
TO ssga_app
USING (app.can_access_employee(employee_id))
WITH CHECK (app.can_access_employee(employee_id));

GRANT SELECT, INSERT ON public.payroll_history_records TO ssga_app;
GRANT USAGE, SELECT
ON SEQUENCE public.payroll_history_records_id_seq TO ssga_app;

INSERT INTO public.schema_migrations (version, name)
VALUES (27, '27_payroll_history_imports')
ON CONFLICT (version) DO NOTHING;

COMMIT;
