-- ---------------------------------------------------------------------------
-- 1. parent_groups
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.parent_groups (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id bigint NOT NULL REFERENCES public.organizations(id),
    name            character varying(150) NOT NULL,
    code            character varying(50)  NOT NULL,
    status          character varying(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at      timestamp with time zone NOT NULL DEFAULT now(),
    updated_at      timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT parent_groups_organization_code_key UNIQUE (organization_id, code),
    CONSTRAINT parent_groups_status_check CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- ---------------------------------------------------------------------------
-- 2. payroll_units
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payroll_units (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_group_id     bigint NOT NULL REFERENCES public.parent_groups(id),
    name                character varying(200) NOT NULL,
    code                character varying(50)  NOT NULL,
    unit_type           character varying(40)  NOT NULL,
    status              character varying(20)  NOT NULL DEFAULT 'ACTIVE',
    verification_status character varying(30)  NOT NULL DEFAULT 'CONFIRMED',
    verification_note   text,
    display_order       smallint NOT NULL DEFAULT 0,
    created_at          timestamp with time zone NOT NULL DEFAULT now(),
    updated_at          timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT payroll_units_code_key UNIQUE (code),
    CONSTRAINT payroll_units_status_check
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT payroll_units_verification_status_check
        CHECK (verification_status IN ('CONFIRMED', 'PENDING_VERIFICATION')),
    CONSTRAINT payroll_units_unit_type_check CHECK (unit_type IN (
        'DIVISION', 'CIRCLE', 'PROJECT_DIVISION', 'PCC',
        'TRANSMISSION_CIRCLE', 'STP_CIRCLE', 'ELECTRICAL_DIVISION',
        'QUALITY_VIGILANCE', 'CENTRAL_STORES', 'BOARD_OFFICE'
    ))
);

CREATE INDEX IF NOT EXISTS ix_payroll_units_parent_group_id
    ON public.payroll_units (parent_group_id);

-- ---------------------------------------------------------------------------
-- 3. employees: stable reference to a payroll unit (no backfill)
-- ---------------------------------------------------------------------------
ALTER TABLE public.employees
    ADD COLUMN IF NOT EXISTS payroll_unit_id bigint
        REFERENCES public.payroll_units(id);

CREATE INDEX IF NOT EXISTS ix_employees_payroll_unit_id
    ON public.employees (payroll_unit_id);

-- ---------------------------------------------------------------------------
-- 4. Grants. Parent groups and payroll units are organizational master data
--    (like organizations / wings): readable by the runtime role, writes are
--    authorized in the application layer (organization.manage). No row level
--    security, mirroring the existing organization master tables.
-- ---------------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE ON public.parent_groups TO ssga_app;
GRANT SELECT, INSERT, UPDATE ON public.payroll_units TO ssga_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ssga_app;

