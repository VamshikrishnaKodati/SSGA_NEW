-- ============================================================================
-- 12_organization_master.sql
--
-- Additive migration for the Organization Master module.
--
-- Target hierarchy (configurable, not hard-wired to the existing Wing/Division
-- tree):
--
--     Organization -> Parent Group -> Payroll Unit -> Employee
--
-- Adds:
--   1. parent_groups      (organization-scoped grouping above payroll units)
--   2. payroll_units      (the operational units: divisions, circles, offices,
--                          PCCs, stores, board office ...)
--   3. employees.payroll_unit_id  (stable internal reference; nullable, NO
--                                  auto-backfill of existing employees)
--   4. read/write grants
--   5. seed: 6 proposed parent groups + the proposed payroll-unit register
--
-- Safe to re-run: every statement is guarded
-- (CREATE TABLE IF NOT EXISTS / ADD COLUMN IF NOT EXISTS / ON CONFLICT).
--
-- IMPORTANT: the seeded unit register is PROPOSED master data reconstructed
-- from the information supplied for this task. Units that could not be
-- confirmed are seeded with verification_status = 'PENDING_VERIFICATION' and a
-- verification_note; they are never deleted. PCC-III (crossed out in the source
-- register) is seeded INACTIVE so it is not activated by default. Parent-group
-- assignments remain fully editable. Review and correct via the application
-- (Organization Master) once the authoritative register is available.
-- ============================================================================

